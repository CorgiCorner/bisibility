const OUT = "lib/deployment/runtime-env.generated.ts";

const baked = {};
for (const key of KEYS) {
  const value = process.env[key];
  if (value != null && value !== "") {
    baked[key] = value;
  }
}

function formatBakedEnv(values) {
  const entries = Object.entries(values);
  if (entries.length === 0) {
    return "{}";
  }

  const lines = entries.map(([key, value]) => {
    const encoded = JSON.stringify(value);
    const inline = `  ${key}: ${encoded},`;
    return inline.length <= 100 ? inline : `  ${key}:\n    ${encoded},`;
  });
  return `{\n${lines.join("\n")}\n}`;
}

function restrictGeneratedFileMode(path) {
  try {
    chmodSync(path, 0o600);
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    console.warn(`[bake-runtime-env] could not chmod ${path} to 0600: ${message}`);
  }
}

const file = `// AUTO-GENERATED by scripts/deploy/bake-runtime-env.mjs at build time. Do not edit or commit.
import "server-only";

const BAKED: Record<string, string> = ${formatBakedEnv(baked)};

// Fill only keys the runtime did not already provide, so platforms that DO
// inject env at request time take precedence over the build-time snapshot.
for (const [key, value] of Object.entries(BAKED)) {
  if (process.env[key] === undefined) {
    process.env[key] = value;
  }
}
`;

// Generated secrets must be owner-only; chmod explicitly because write mode applies only on create.
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, file, { mode: 0o600 });
restrictGeneratedFileMode(OUT);
console.log(
  `[bake-runtime-env] wrote ${OUT} with ${Object.keys(baked).length} key(s): ${Object.keys(baked).join(", ") || "(none)"}`,
);
