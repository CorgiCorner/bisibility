const OUT = "lib/deployment/runtime-env.generated.ts";

function formatBakedEnv(values) {
  const entries = Object.entries(values);
  if (entries.length === 0) {
    return "{}";
  }

  const lines = entries.map(([key, value]) => {
    const encoded = JSON.stringify(value);
    const inline = `  ${key}: ${encoded},`;
    return inline.length <= 100 ? inline : `  ${key}:\n    ${encoded},`;
  });
  return `{\n${lines.join("\n")}\n}`;
}

export function collectBakedEnvironment(env = process.env) {
  const baked = {};
  for (const key of KEYS) {
    const value = env[key];
    if (value != null && value !== "") {
      baked[key] = value;
    }
  }
  return baked;
}

export function renderBakedRuntimeEnvironment(env = process.env) {
  const baked = collectBakedEnvironment(env);
  const revision = /^[0-9a-f]{40}$/.test(baked.APP_REVISION ?? "")
    ? baked.APP_REVISION
    : "unknown";
  return `// AUTO-GENERATED by scripts/deploy/bake-runtime-env.mjs at build time. Do not edit or commit.
import "server-only";

const BAKED: Record<string, string> = ${formatBakedEnv(baked)};

// Read identity from the generated module, never from mutable runtime env.
export const getBakedAppRevision = () => ${JSON.stringify(revision)};

// Fill only keys the runtime did not already provide, so platforms that DO
// inject env at request time take precedence over the build-time snapshot.
for (const [key, value] of Object.entries(BAKED)) {
  if (process.env[key] === undefined) {
    process.env[key] = value;
  }
}
`;
}

export function writeBakedRuntimeEnvironment({
  env = process.env,
  outputPath = OUT,
} = {}) {
  const baked = collectBakedEnvironment(env);
  const file = renderBakedRuntimeEnvironment(env);
  // Generated secrets must be owner-only; chmod explicitly because write mode applies only on create.
  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, file, { mode: 0o600 });
  chmodSync(outputPath, 0o600);
  console.log(
    `[bake-runtime-env] wrote ${outputPath} with ${Object.keys(baked).length} key(s): ${Object.keys(baked).join(", ") || "(none)"}`,
  );
}

export function checkBakedRuntimeEnvironment({
  env = process.env,
  outputPath = OUT,
} = {}) {
  let actual;
  let mode;
  try {
    actual = readFileSync(outputPath, "utf8");
    mode = statSync(outputPath).mode & 0o777;
  } catch {
    throw new Error(`[bake-runtime-env] ${outputPath} is missing or unreadable`);
  }
  if (actual !== renderBakedRuntimeEnvironment(env) || mode !== 0o600) {
    throw new Error(`[bake-runtime-env] ${outputPath} does not match the current environment`);
  }
  console.log(`[bake-runtime-env] verified ${outputPath}`);
}

export function main(args = process.argv.slice(2)) {
  if (args.length === 0) {
    writeBakedRuntimeEnvironment();
    return;
  }
  if (args.length === 1 && args[0] === "--check") {
    checkBakedRuntimeEnvironment();
    return;
  }
  throw new Error("Usage: bake-runtime-env.mjs [--check]");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    main();
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}
