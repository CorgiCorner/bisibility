export function renderCliReference(version, sections) {
  const checkCompatibility = `<Warning>
The published help below uses legacy wording for \`--async\`. With the current
API, this flag does not select execution mode; deployment configuration does.
A completed inline check returns HTTP \`201\`. A queued request returns HTTP
\`202\` with \`status: queued\` and a run ID, not a completed check ID.
See [Checks](/api/checks) for polling and result correlation.
</Warning>\n\n`;
  return `---
title: "CLI command reference"
description: "Commands and options extracted from the published Bisibility CLI ${version}."
---

{/* Generated by scripts/generate/docs-ecosystem.mjs. */}

This reference reproduces the help shipped in \`@bisibility/cli@${version}\`.
Start with the [CLI quickstart](/cli) for authentication and project selection.
Use \`bisibility --version\` to compare your installation with this reference;
\`bisibility <command> --help\` describes your installed version.

Commands that write data or query a provider require the corresponding scope
and may incur provider charges. Consult the command's help before running it.
See [released client support](/compatibility) for artifact provenance.

${sections.map(({ title, text }) => `## ${title}\n\n${title === "check" ? checkCompatibility : ""}\`\`\`text\n${text}\n\`\`\`\n`).join("\n")}`;
}
