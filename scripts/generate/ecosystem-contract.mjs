import { createHash } from "node:crypto";

export function digest(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

export function verifyDigest(bytes, expected) {
  if (!/^[a-f0-9]{64}$/.test(expected) || digest(bytes) !== expected) {
    throw new Error("Published artifact checksum mismatch");
  }
}

export function sourceFromArtifact(text, artifact) {
  if (!artifact.source) return text;
  const map = JSON.parse(text);
  const index = map.sources.indexOf(artifact.source);
  if (index < 0 || typeof map.sourcesContent?.[index] !== "string") {
    throw new Error(`Missing published source: ${artifact.source}`);
  }
  return map.sourcesContent[index];
}

export function verifyOperations(source, artifact) {
  const lines = source.split(/\r?\n/);
  for (const operation of artifact.operations) {
    if (!/^[A-Za-z][A-Za-z_ -]*$/.test(operation)) throw new Error("Invalid operation name");
    const prefixes = {
      typescript: `    ${operation}(`,
      python: `    def ${operation}(`,
      go: `func (c *Client) ${operation}(`,
      cli: `  bisibility ${operation} <target>`,
      mcp: `    "${operation}",`,
    };
    const prefix = prefixes[artifact.declaration];
    if (!prefix || !lines.some((line) => line.startsWith(prefix))) {
      throw new Error(`${artifact.id}: missing published operation ${operation}`);
    }
  }
}

export function extractCliHelp(source, version) {
  const sections = [];
  const functions = [...source.matchAll(/export function (\w+Help)\(\)/g)];
  for (const match of source.matchAll(/export function (\w+Help)\(\) \{\s*return `([^`]+)`;\s*\}/g)) {
    const text = match[2].replaceAll("${VERSION}", version);
    if (text.includes("${")) throw new Error(`Unsupported help interpolation: ${match[1]}`);
    const title = match[1] === "mainHelp" ? "Commands and global options"
      : match[1].replace(/Help$/, "").replaceAll(/([a-z])([A-Z])/g, "$1 $2").toLowerCase();
    sections.push({ title, text: text.trimEnd() });
  }
  if (!sections.length || sections.length !== functions.length) {
    throw new Error("CLI help format changed; update the extractor before publishing");
  }
  return sections;
}

