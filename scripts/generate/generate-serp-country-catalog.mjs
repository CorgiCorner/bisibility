import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

// Generate ISO-keyed country metadata from the committed location catalog.

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(scriptDir, "../..");
const countriesPath = path.join(rootDir, "scripts/generate/sources/markets/countries.json");
const languagesPath = path.join(rootDir, "lib/serp/generated/serp-language-catalog.ts");
const outputPath = path.join(rootDir, "lib/serp/generated/serp-country-catalog.ts");

/** Validate the code-keyed source before any generator consumes it. */
export function countryDeclarations(source) {
  const entries = JSON.parse(source);
  if (!Array.isArray(entries) || entries.length === 0 || entries.some((entry) =>
    !/^[A-Z]{2}$/.test(entry.countryCode) || typeof entry.displayName !== "string" ||
    !entry.displayName.trim() || typeof entry.languageCode !== "string" ||
    !Array.isArray(entry.aliases) || entry.aliases.some((alias) => typeof alias !== "string")
  )) {
    throw new Error("Invalid country catalog source.");
  }
  if (new Set(entries.map((entry) => entry.countryCode)).size !== entries.length) {
    throw new Error("The country catalog contains duplicate country codes.");
  }
  return entries;
}

/** The `{ code, label }` rows of the generated SERP language catalog, keyed by code. */
export function languageLabels(languageCatalogSource) {
  const labels = new Map();
  const rowPattern = /\{\s*code:\s*"([^"]+)",\s*label:\s*"([^"]+)"\s*\}/gu;
  for (const match of languageCatalogSource.matchAll(rowPattern)) {
    labels.set(match[1], match[2]);
  }
  if (labels.size === 0) {
    throw new Error("Could not read the SERP language catalog.");
  }
  return labels;
}

export function countryCatalog(countriesSource, languageCatalogSource) {
  const labels = languageLabels(languageCatalogSource);
  const entries = countryDeclarations(countriesSource).map((declaration) => {
    const languageLabel = labels.get(declaration.languageCode);
    if (!languageLabel) {
      throw new Error(`Unsupported default language: ${declaration.languageCode}`);
    }
    return { ...declaration, languageLabel };
  });
  if (new Set(entries.map((entry) => entry.countryCode)).size !== entries.length) {
    throw new Error("The country catalog contains duplicate country codes.");
  }
  return entries.sort((left, right) => left.countryCode.localeCompare(right.countryCode));
}

function renderCatalog(entries) {
  const lines = [
    "/*",
    " * Generated by scripts/generate/generate-serp-country-catalog.mjs.",
    " * Do not edit manually. Regenerate from scripts/generate/sources/markets/countries.json and",
    " * the generated SERP language catalog.",
    " */",
    "",
    "export type SerpCountryCatalogEntry = {",
    "  aliases: readonly string[];",
    "  countryCode: string;",
    "  displayName: string;",
    "  languageCode: string;",
    "  languageLabel: string;",
    "};",
    "",
    "// biome-ignore format: Keep each generated country on one line, like the language catalog.",
    "export const serpCountryCatalog: readonly SerpCountryCatalogEntry[] = [",
    ...entries.map((entry) =>
      `  { aliases: [${entry.aliases.map((alias) => JSON.stringify(alias)).join(", ")}], countryCode: ${JSON.stringify(entry.countryCode)}, displayName: ${JSON.stringify(entry.displayName)}, languageCode: ${JSON.stringify(entry.languageCode)}, languageLabel: ${JSON.stringify(entry.languageLabel)} },`,
    ),
    "];",
    "",
  ];
  return lines.join("\n");
}

async function main() {
  const [countriesSource, languageCatalogSource] = await Promise.all([
    fs.readFile(countriesPath, "utf8"),
    fs.readFile(languagesPath, "utf8"),
  ]);
  const output = renderCatalog(countryCatalog(countriesSource, languageCatalogSource));
  if (process.argv.includes("--check")) {
    const current = await fs.readFile(outputPath, "utf8").catch(() => "");
    if (current !== output) {
      throw new Error(`Generated catalog is stale: ${path.relative(rootDir, outputPath)}`);
    }
    return;
  }
  await fs.mkdir(path.dirname(outputPath), { recursive: true });
  await fs.writeFile(outputPath, output);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
